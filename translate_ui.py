def quote_safe(text, q):
    """Escape the outer quote character if the English text contains it."""
    out, i = [], 0
    while i < len(text):
        c = text[i]
        if c == "\\" and i + 1 < len(text):
            out.append(text[i:i + 2]); i += 2; continue
        out.append("\\" + c if c == q else c)
        i += 1
    return "".join(out)


def main():
    if not os.path.isdir(LIB):
        print("Run this from the repo root (the folder that contains lib/)."); sys.exit(1)
    table = sorted(TABLE, key=lambda p: len(p[0]), reverse=True)
    changed_files, total_repl = 0, 0
    leftovers, comment_lines = [], {}
    for root, _, files in os.walk(LIB):
        for name in sorted(files):
            if not name.endswith(".dart"):
                continue
            path = os.path.join(root, name)
            with open(path, encoding="utf-8") as f:
                text = f.read()
            new = text
            for hi, en in CONTEXT_FIXES:
                if hi in new:
                    new = new.replace(hi, en); total_repl += 1
            for hi, en in table:
                for q in ("'", '"'):
                    pat = q + hi + q
                    if pat in new:
                        total_repl += new.count(pat)
                        new = new.replace(pat, q + quote_safe(en, q) + q)
            if new != text:
                changed_files += 1
                print(("UPDATED  " if WRITE else "WOULD UPDATE  ") + path)
                if WRITE:
                    with open(path, "w", encoding="utf-8") as f:
                        f.write(new)
            for i, line in enumerate(new.split("\n"), 1):
                if DEV.search(line):
                    if line.strip().startswith("//") or "//" in line.split("'")[-1]:
                        comment_lines[path] = comment_lines.get(path, 0) + 1
                    else:
                        leftovers.append((path, i, line.strip()[:120]))
    print("\nFiles changed: %d   Strings replaced: %d" % (changed_files, total_repl))
    if leftovers:
        print("\nHindi still in CODE (send me these lines):")
        for p, i, l in leftovers:
            print("  %s:%d  %s" % (p, i, l))
    else:
        print("\nNo Hindi text left in code strings.")
    if comment_lines:
        print("\nHindi only in developer comments (never shown in the app):")
        for p, n in sorted(comment_lines.items()):
            print("  %s: %d comment lines" % (p, n))
    if not WRITE:
        print("\nDry run only. Add --write to apply.")


